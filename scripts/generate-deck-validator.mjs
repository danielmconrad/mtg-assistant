// Compiles schemas/deck.schema.json into a standalone validator module. Ajv normally compiles schemas
// into code at runtime, which Workers forbid; the standalone module is that same code, generated ahead
// of time and committed, so validation and its error messages match mtg-manager exactly.
//
//   node scripts/generate-deck-validator.mjs           # rewrite the module
//   node scripts/generate-deck-validator.mjs --check   # fail if it's out of date (tests run this)
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';

export const SCHEMA_PATH = 'schemas/deck.schema.json';
export const OUTPUT_PATH = 'src/core/deck-validator.generated.mjs';

// Ajv's standalone output still requires one CommonJS runtime helper, which an ES module can't load in
// Workers. It's Ajv's own code-point counter, inlined here (MIT, from ajv/dist/runtime/ucs2length.js).
const UCS2LENGTH_REQUIRE = 'require("ajv/dist/runtime/ucs2length").default';
const UCS2LENGTH = `function ucs2length(str) {
  const len = str.length;
  let length = 0;
  let pos = 0;
  let value;
  while (pos < len) {
    length++;
    value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      value = str.charCodeAt(pos);
      if ((value & 0xfc00) === 0xdc00) pos++;
    }
  }
  return length;
}`;

export async function generate() {
  const schema = JSON.parse(await readFile(SCHEMA_PATH, 'utf8'));
  const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
  const code = standaloneCode(ajv, ajv.compile(schema)).replaceAll(UCS2LENGTH_REQUIRE, 'ucs2length');
  if (/\brequire\(/.test(code)) throw new Error('The generated validator still requires a CommonJS module');
  return `// Generated by scripts/generate-deck-validator.mjs from ${SCHEMA_PATH}. Don't edit by hand.\n/* eslint-disable */\n${UCS2LENGTH}\n${code}\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const code = await generate();
  if (process.argv.includes('--check')) {
    const current = await readFile(OUTPUT_PATH, 'utf8').catch(() => '');
    if (current !== code) {
      console.error(`${OUTPUT_PATH} is out of date: run node scripts/generate-deck-validator.mjs`);
      process.exitCode = 1;
    }
  } else {
    await writeFile(OUTPUT_PATH, code);
    console.log(`Wrote ${OUTPUT_PATH}`);
  }
}
